const modulePath = process.env.ATLAS_NODE_MODULES || require('node:path').join(process.env.USERPROFILE || process.env.HOME, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules');
const { chromium } = require(require.resolve('playwright', {paths:[process.cwd(),modulePath]}));
const path = require('node:path');
const fs = require('node:fs');
const {pathToFileURL} = require('node:url');
(async()=>{
const root=path.resolve(__dirname,'..');
let browser;
try {browser=await chromium.launch({headless:true});}
catch {browser=await chromium.launch({headless:true,channel:'msedge'});}
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(pathToFileURL(path.join(root,'index.html')).href);
await page.waitForSelector('.figure-card');
const assert=(v,m)=>{if(!v)throw Error(m);};
assert(await page.locator('.figure-card').count()===52,'initial figure count');
await page.locator('#search').fill('SHAP');
assert(await page.locator('.figure-card').count()===1,'SHAP search');
await page.locator('#reset').click();
await page.locator('[data-category="MDP 框架"]').click();
assert(await page.locator('.figure-card').count()===6,'MDP category count');
await page.locator('#reset').click();
await page.locator('#availability').selectOption('original');
assert(await page.locator('.figure-card').count()===35,'original image count');
const first=page.locator('.save').first();await first.click();
await page.locator('#shortlist-filter').click();
assert(await page.locator('.figure-card').count()===1,'shortlist filter');
const fileEvent=page.waitForEvent('download');await page.locator('#export').click();
const downloaded=await fileEvent;await downloaded.saveAs(path.join(root,'.cache','shortlist-check.md'));
assert(fs.readFileSync(path.join(root,'.cache','shortlist-check.md'),'utf8').includes('https://doi.org/'),'export includes citation');
await page.locator('#reset').click();
await page.screenshot({path:path.join(root,'.cache','gallery-desktop.png'),fullPage:false});
await page.locator('[data-view="templates"]').click();
assert(await page.locator('.template-item').count()===10,'template count');
await page.locator('.template-item img').evaluateAll(images=>Promise.all(images.map(i=>{i.loading='eager';return i.decode();})));
await page.screenshot({path:path.join(root,'.cache','templates-desktop.png'),fullPage:false});
await page.locator('[data-view="workbench"]').click();
await page.locator('[name="agent"]').fill('测试管理者');
assert((await page.locator('#mdp-preview').textContent()).includes('测试管理者'),'live preview');
await page.locator('[name="model"]').selectOption('POMDP');
assert((await page.locator('#mermaid-code').textContent()).includes('信念'),'POMDP semantics');
const svgEvent=page.waitForEvent('download');await page.locator('#download-svg').click();
const svg=await svgEvent;await svg.saveAs(path.join(root,'.cache','workbench-check.svg'));
await page.locator('[name="agent"]').fill('流域管理者');await page.locator('[name="model"]').selectOption('MDP');
await page.screenshot({path:path.join(root,'.cache','workbench-desktop.png'),fullPage:false});
await page.locator('[data-view="papers"]').click();assert(await page.locator('.paper-row').count()===16,'paper list');
await page.locator('[data-view="gallery"]').click();
await page.setViewportSize({width:390,height:844});await page.screenshot({path:path.join(root,'.cache','gallery-mobile.png'),fullPage:false});
assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no mobile horizontal overflow');
const broken=await page.locator('#gallery img').evaluateAll(images=>images.filter(i=>i.complete&&i.naturalWidth===0).map(i=>i.src));
assert(!broken.length,'no broken images');assert(!errors.length,errors.join('\n'));
console.log('PASS browser: filters, search, shortlist export, 10 templates, MDP preview and download, POMDP text, paper index, mobile layout, no page errors.');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
